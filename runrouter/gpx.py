"""GPX 1.1 serialization for running routes."""

from __future__ import annotations

import xml.etree.ElementTree as ET
from datetime import datetime, timezone

_NS = "http://www.topografix.com/GPX/1/1"


def _fmt(value: float) -> str:
    return f"{value:.7f}"


def to_gpx(
    name: str,
    coords: list[tuple[float, float]],
    *,
    distance_m: float,
    duration_s: float,
    creator: str = "RunRouter",
) -> str:
    """Serialize a route as a GPX 1.1 track.

    ``coords`` is a list of ``(lat, lon)`` tuples.
    """
    gpx = ET.Element(
        "gpx",
        {
            "version": "1.1",
            "creator": creator,
            "xmlns": _NS,
            "xmlns:xsi": "http://www.w3.org/2001/XMLSchema-instance",
            "xsi:schemaLocation": (
                f"{_NS} {_NS}/gpx.xsd"
            ),
        },
    )

    metadata = ET.SubElement(gpx, "metadata")
    ET.SubElement(metadata, "name").text = name
    ET.SubElement(metadata, "time").text = datetime.now(timezone.utc).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )
    ET.SubElement(metadata, "desc").text = (
        f"Running route generated by {creator}. "
        f"Distance: {distance_m / 1000:.2f} km, "
        f"duration: {duration_s / 60:.1f} min."
    )

    trk = ET.SubElement(gpx, "trk")
    ET.SubElement(trk, "name").text = name
    ET.SubElement(trk, "type").text = "running"

    trkseg = ET.SubElement(trk, "trkseg")
    for lat, lon in coords:
        ET.SubElement(trkseg, "trkpt", {"lat": _fmt(lat), "lon": _fmt(lon)})

    ET.indent(gpx, space="  ")
    return ET.tostring(gpx, encoding="unicode", xml_declaration=True)
